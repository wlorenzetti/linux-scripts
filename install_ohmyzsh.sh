#!/usr/bin/env bash
# ============================================================
#  setup-zsh.sh
#  Installs zsh + Oh My Zsh + plugins + Agnoster theme
#  Ubuntu 26.04
# ============================================================

set -e  # exits immediately if a command fails

echo "==> 1/7 Updating packages and installing dependencies..."
sudo apt update
sudo apt install -y zsh curl git fonts-powerline

echo "==> 2/7 Installing Oh My Zsh (unattended)..."
if [ -d "$HOME/.oh-my-zsh" ]; then
  echo "Oh My Zsh is already installed, skipping this step."
else
  RUNZSH=no CHSH=no KEEP_ZSHRC=yes \
  sh -c "$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)"
fi

ZSH_CUSTOM="${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}"

echo "==> 3/7 Installing zsh-autosuggestions plugin..."
if [ -d "$ZSH_CUSTOM/plugins/zsh-autosuggestions" ]; then
  echo "Already present, skipping."
else
  git clone https://github.com/zsh-users/zsh-autosuggestions "$ZSH_CUSTOM/plugins/zsh-autosuggestions"
fi

echo "==> 4/7 Installing zsh-syntax-highlighting plugin..."
if [ -d "$ZSH_CUSTOM/plugins/zsh-syntax-highlighting" ]; then
  echo "Already present, skipping."
else
  git clone https://github.com/zsh-users/zsh-syntax-highlighting "$ZSH_CUSTOM/plugins/zsh-syntax-highlighting"
fi

echo "==> 5/7 Installing Agnoster theme..."
if [ -d "$ZSH_CUSTOM/themes/agnoster" ]; then
  echo "Already present, skipping."
else
  git clone https://github.com/agnoster/agnoster-zsh-theme.git "$ZSH_CUSTOM/themes/agnoster"
fi
ln -sf "$ZSH_CUSTOM/themes/agnoster/agnoster.zsh-theme" "$ZSH_CUSTOM/themes/agnoster.zsh-theme"

echo "==> 6/7 Writing ~/.zshrc..."
if [ -f "$HOME/.zshrc" ]; then
  cp "$HOME/.zshrc" "$HOME/.zshrc.bak.$(date +%s)"
  echo "Backup of the existing .zshrc created."
fi

cat > "$HOME/.zshrc" << 'EOF'
# ============================================================
#  .zshrc - Oh My Zsh configuration (generated by setup-zsh.sh)
# ============================================================

export ZSH="$HOME/.oh-my-zsh"

ZSH_THEME="agnoster"

plugins=(
  git
  sudo
  z
  colored-man-pages
  command-not-found
  zsh-autosuggestions
  zsh-syntax-highlighting
)

source $ZSH/oh-my-zsh.sh

export EDITOR='nano'
export VISUAL='nano'

HISTSIZE=10000
SAVEHIST=10000
HISTFILE=~/.zsh_history
setopt HIST_IGNORE_DUPS
setopt HIST_IGNORE_SPACE
setopt SHARE_HISTORY

alias ll='ls -alF'
alias la='ls -A'
alias l='ls -CF'
alias ..='cd ..'
alias ...='cd ../..'
alias grep='grep --color=auto'
alias update='sudo apt update && sudo apt upgrade -y'
alias c='clear'
alias h='history'

alias gs='git status'
alias ga='git add'
alias gc='git commit -m'
alias gp='git push'
alias gl='git log --oneline --graph --decorate'
EOF

echo "==> 7/7 Setting zsh as the default shell..."
if [ "$SHELL" != "$(which zsh)" ]; then
  chsh -s "$(which zsh)"
  echo "Default shell changed to zsh. Log out and back in to apply."
else
  echo "zsh is already the default shell."
fi

echo ""
echo "============================================================"
echo " Installation completed!"
echo " IMPORTANT: set a Powerline/Nerd Font in your"
echo " terminal emulator (e.g. 'MesloLGS NF'), otherwise"
echo " you will see strange symbols instead of theme icons."
echo ""
echo " Then start a new zsh session with: exec zsh"
echo "============================================================"
